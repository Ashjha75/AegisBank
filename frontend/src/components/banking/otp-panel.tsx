"use client";

import { ShieldCheck } from "lucide-react";
import * as React from "react";
import { toast } from "sonner";
import { Alert } from "@/components/ui/alert";
import { Amount } from "@/components/ui/amount";
import { Button } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { Field } from "@/components/ui/field";
import { Input } from "@/components/ui/input";
import { useVerifyOtp } from "@/lib/api/banking";
import { userMessageFor } from "@/lib/api/error-messages";
import { isApiError } from "@/lib/api/problem";
import type { TransactionResponse } from "@/lib/api/types";
import { formatAccountNumber } from "@/lib/format";

const OTP_LENGTH = 6;

/**
 * Releases a transfer that fraud-detection held back.
 *
 * The code itself is generated by transaction-service, kept in Redis and sent over the
 * `transaction.otp.generated` topic to notification-service - it never travels to this UI.
 * A wrong code answers 422 INVALID_OTP; too many wrong ones (or an expired code) refund the
 * sender and FLAG the transfer, which the parent sees on the next render of `transaction`.
 */
export function OtpPanel({
  transaction,
}: {
  transaction: TransactionResponse;
}) {
  const [otp, setOtp] = React.useState("");
  const [error, setError] = React.useState<string | undefined>();
  const verify = useVerifyOtp(transaction.id);

  const submit = async (event: React.FormEvent) => {
    event.preventDefault();
    const code = otp.replace(/\s/g, "");
    if (!/^\d{6}$/.test(code)) {
      setError("Enter the 6 digits of the code.");
      return;
    }
    setError(undefined);
    try {
      const updated = await verify.mutateAsync(code);
      setOtp("");
      if (updated.status === "COMPLETED") {
        toast.success("Transfer released", {
          description: "The receiver has been credited.",
        });
      } else {
        toast.info("Transfer updated", {
          description: `This transfer is now ${updated.status.toLowerCase().replace(/_/g, " ")}.`,
        });
      }
    } catch (caught) {
      setError(
        isApiError(caught)
          ? userMessageFor(caught).message
          : "Something went wrong. Please try again.",
      );
    }
  };

  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2">
          <ShieldCheck className="size-4 text-brand" aria-hidden="true" />
          Confirm this transfer
        </CardTitle>
        <CardDescription>
          This transfer is large enough to need a one-time code. We sent it to
          the contact details on the sending account.
        </CardDescription>
      </CardHeader>
      <CardContent className="grid gap-5">
        <div className="flex flex-wrap items-center gap-x-2 gap-y-1 rounded-md border border-border bg-surface-subtle px-4 py-3 text-body-sm">
          <Amount value={transaction.amount} />
          <span className="text-muted-foreground">to</span>
          <span className="font-mono">
            {formatAccountNumber(transaction.receiverAccountNumber)}
          </span>
        </div>

        <form onSubmit={submit} className="grid gap-4" noValidate>
          <Field
            label="One-time code"
            hint="6 digits. The code expires a few minutes after it is sent."
            error={error}
          >
            <Input
              value={otp}
              onChange={(event) =>
                setOtp(
                  event.target.value.replace(/\D/g, "").slice(0, OTP_LENGTH),
                )
              }
              inputMode="numeric"
              autoComplete="one-time-code"
              placeholder="000000"
              maxLength={OTP_LENGTH}
              className="max-w-40 text-center font-mono text-amount tracking-[0.3em]"
            />
          </Field>
          <div className="flex flex-wrap gap-2">
            <Button
              type="submit"
              variant="brand"
              loading={verify.isPending}
              disabled={otp.length !== OTP_LENGTH}
            >
              Confirm transfer
            </Button>
          </div>
        </form>

        <Alert tone="warning" title="If you did not start this transfer">
          Do not enter the code. Without it the transfer is refunded to the
          sending account automatically.
        </Alert>
      </CardContent>
    </Card>
  );
}
